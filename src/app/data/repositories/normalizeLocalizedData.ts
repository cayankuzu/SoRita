export function normalizeLocalizedText(value: string) {
  return TURKISH_TEXT_FIXES.reduce(
    (text, [from, to]) => text.split(from).join(to),
    value,
  );
}

export function normalizeLocalizedData<T>(value: T): T {
  if (typeof value === 'string') {
    return normalizeLocalizedText(value) as T;
  }

  if (Array.isArray(value)) {
    return value.map((item) => normalizeLocalizedData(item)) as T;
  }

  if (value && typeof value === 'object') {
    return Object.fromEntries(
      Object.entries(value).map(([key, nestedValue]) => [key, normalizeLocalizedData(nestedValue)]),
    ) as T;
  }

  return value;
}
